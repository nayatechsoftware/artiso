function Block({ block }) {
  if (block.h3) {
    return <h3 className="mt-8 text-[13px] uppercase tracking-[0.16em] text-black/50">{block.h3}</h3>;
  }
  if (block.h4) {
    return <h4 className="mt-6 text-[15px] font-medium text-black">{block.h4}</h4>;
  }
  if (block.ul) {
    return (
      <ul className="mt-4 space-y-2.5">
        {block.ul.map((item, index) => {
          const entry = typeof item === "string" ? { p: item } : item;
          return (
            <li key={index} className="flex gap-3 text-[15px] leading-relaxed text-black/60">
              <span className="mt-2 h-1 w-1 shrink-0 rounded-full bg-black/35" />
              <span>
                {entry.strong && <strong className="font-medium text-black">{entry.strong} </strong>}
                {entry.p}
              </span>
            </li>
          );
        })}
      </ul>
    );
  }
  return <p className="mt-4 text-[15px] leading-relaxed text-black/60">{block.p}</p>;
}

